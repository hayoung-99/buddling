/**
 * 이름 없이 만든 방에 붙일 이름.
 *
 * 예전에는 데이터베이스가 `'우리 팀'` 이라는 한국어를 채워 넣었다. 그래서 일본어를
 * 쓰는 사람이 이름 없이 방을 만들면 한국어 이름이 나왔다. 이제는 앱이 자기 말로
 * 채워 보내고, 스키마는 옛 앱을 위한 안전망만 남긴다.
 *
 * **채우는 자리는 화면이 아니라 여기다.** 처음에는 만들기 폼에서 채웠는데, 그러면
 * 폼을 거치지 않는 경로(개발용 캡처처럼 IPC 를 바로 부르는 것)가 전부 안전망 이름을
 * 받는다. 규칙 3 대로 **문장을 만드는 일은 `main/ipc.ts` 의 몫**이고, 거기에는 지금
 * 쓰는 언어도 내가 속한 방 목록도 이미 있다.
 *
 * **번호는 정규식으로 뽑지 않고 만들어 보며 찾는다.** 사전이 언어마다 다른 문장을
 * 주므로("이름없음 {n}" · "Untitled {n}") 이름에서 숫자를 되읽으려면 언어마다 다른
 * 규칙이 필요해진다. 대신 1번부터 만들어 보고 안 쓰이는 첫 번째를 고르면, 문장이
 * 어떻게 생겼든 상관이 없다.
 */

/**
 * @param format 번호를 받아 이름을 만든다 (`(n) => t('form.teamNameDefault', { n })`)
 * @param taken  이미 쓰이고 있는 이름들. 내가 속한 방 이름을 넘긴다
 */
export function nextDefaultName(format: (n: number) => string, taken: Iterable<string>): string {
  const used = new Set([...taken].map((name) => name.trim()))

  // 한 사람이 가질 수 있는 방은 세 개뿐이라 이 고리는 길어야 네 바퀴다.
  let n = 1
  while (used.has(format(n))) n += 1
  return format(n)
}
